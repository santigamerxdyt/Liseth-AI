"""
Cryptographic module for JARVIS / Liseth
Implements AES-256-GCM encryption with 100% interoperability with Node.js crypto.js.
Also provides secure scrypt password/PIN hashing and verification.
"""
import os
import hashlib
import hmac
import secrets
from typing import Optional, Tuple
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from app.config import settings


def get_master_key(secret: Optional[str] = None) -> bytes:
    """
    Derives a 32-byte AES-256 key using SHA-256, matching Node.js getMasterKey().
    """
    raw_secret = secret if secret is not None else settings.MASTER_ENCRYPTION_KEY
    if not raw_secret:
        raw_secret = "jarvis-liseth-default-secure-key-32b"
    return hashlib.sha256(raw_secret.encode("utf-8")).digest()


def encrypt(text: str, secret: Optional[str] = None) -> str:
    """
    Encrypts a string using AES-256-GCM.
    Returns: 'iv_hex:tag_hex:ciphertext_hex' exactly compatible with Node.js crypto.js.
    """
    if not text:
        return ""

    key = get_master_key(secret)
    aesgcm = AESGCM(key)
    iv = os.urandom(16)  # 16-byte nonce / IV

    # AESGCM.encrypt appends the 16-byte authentication tag at the end of the ciphertext
    ct_with_tag = aesgcm.encrypt(iv, text.encode("utf-8"), None)
    ciphertext = ct_with_tag[:-16]
    tag = ct_with_tag[-16:]

    return f"{iv.hex()}:{tag.hex()}:{ciphertext.hex()}"


def decrypt(cipher_text: str, secret: Optional[str] = None) -> Optional[str]:
    """
    Decrypts a string generated by either this module or Node.js crypto.js.
    Format: 'iv_hex:tag_hex:ciphertext_hex'
    """
    if not cipher_text or not isinstance(cipher_text, str) or ":" not in cipher_text:
        return cipher_text

    try:
        parts = cipher_text.split(":")
        if len(parts) != 3:
            return cipher_text

        iv_hex, tag_hex, ct_hex = parts
        iv = bytes.fromhex(iv_hex)
        tag = bytes.fromhex(tag_hex)
        ciphertext = bytes.fromhex(ct_hex)

        key = get_master_key(secret)
        aesgcm = AESGCM(key)

        # AESGCM in cryptography expects ciphertext + tag combined
        decrypted_bytes = aesgcm.decrypt(iv, ciphertext + tag, None)
        return decrypted_bytes.decode("utf-8")
    except Exception as e:
        # Cryptographic failure or tampering
        return None


def generate_secure_key(num_bytes: int = 32) -> str:
    """
    Generates a cryptographically strong hex string.
    """
    return secrets.token_hex(num_bytes)


# --- Scrypt PIN Hashing & Verification ---

SCRYPT_N = 16384
SCRYPT_R = 8
SCRYPT_P = 1
SCRYPT_KEY_LEN = 32


def hash_pin(pin: str, salt: Optional[bytes] = None) -> Tuple[str, str]:
    """
    Hashes a PIN using scrypt.
    Returns: (salt_hex, hash_hex)
    """
    if salt is None:
        salt = os.urandom(16)
    derived = hashlib.scrypt(
        pin.encode("utf-8"),
        salt=salt,
        n=SCRYPT_N,
        r=SCRYPT_R,
        p=SCRYPT_P,
        maxmem=0,
        dklen=SCRYPT_KEY_LEN
    )
    return salt.hex(), derived.hex()


def verify_pin(pin: str, salt_hex: str, hash_hex: str) -> bool:
    """
    Verifies a PIN against its scrypt salt and hash in constant time.
    """
    try:
        salt = bytes.fromhex(salt_hex)
        expected_hash = bytes.fromhex(hash_hex)
        computed = hashlib.scrypt(
            pin.encode("utf-8"),
            salt=salt,
            n=SCRYPT_N,
            r=SCRYPT_R,
            p=SCRYPT_P,
            maxmem=0,
            dklen=SCRYPT_KEY_LEN
        )
        return hmac.compare_digest(computed, expected_hash)
    except Exception:
        return False
